    private void comboConsolaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_comboConsolaActionPerformed
      String consola = comboConsola.getSelectedItem().toString();

    if (consola.equals("Todas")) {
        tablaJuegos.setModel(
                new JuegosTableModel(juegoDAO.obtenerTodos()));
    } else {
        tablaJuegos.setModel(
                new JuegosTableModel(juegoDAO.obtenerPorConsola(consola)));
    }
    }//GEN-LAST:event_comboConsolaActionPerformed

